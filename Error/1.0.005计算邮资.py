# ## 题目描述

# 请根据邮件的重量和用户选择是否加急计算邮费。计算规则：

# - 重量在 $1000$ 以内（包括），基本费 $8$ 元；

# - 超过 $1000$ 克的部分，每 $500$ 克加收超重费 $4$ 元，不足 $500$ 克部分按 $500$ 克计算；

# - 如果用户选择加急，多收 $5$ 元。

# ## 输入格式

# 一行，包含一个正整数 $x$ 和一个字符 c(`y` 或 `n`)，之间用一个空格隔开，分别表示重量和是否加急。

# 如果字符是 `y`，说明选择加急；如果字符是 `n`，说明不加急。

# ## 输出格式

# 输出一行一个正整数，表示邮费。

# ## 输入输出样例 #1

# ### 输入 #1

# ```
# 1200 y
# ```

# ### 输出 #1

# ```
# 17
# ```

# ## 说明/提示

# 对于100%数据 $1\leq x\leq 10^6$