# 读取输入并解析
weight, urgent = input().split()
weight = int(weight)
base_fee = 8

# 计算基础费用
if weight > 1000:
    # 计算超过1000克的部分需要多少个500克（向上取整）
    extra_units = (weight - 1000 + 499) // 500
    base_fee += extra_units * 4

# 计算总费用（包括加急费）
total_fee = base_fee + (5 if urgent == 'y' else 0)

print(total_fee)

