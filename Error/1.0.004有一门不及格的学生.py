# # B2044 有一门课不及格的学生

# ## 题目描述

# 给出一名学生的语文、数学、英语成绩，判断他是否恰好有一门课不及格（成绩小于 $60$ 分）。若该学生恰好有一门成绩不及格输出 $1$，否则输出 $0$。

# ## 输入格式

# 一行包含三个 $0 \sim 100$ 之间的整数，分别表示该生的语文、数学、英语成绩。

# ## 输出格式

# 该学生恰好有一门成绩不及格输出 $1$，否则输出 $0$。

# ## 输入输出样例 #1

# ### 输入 #1

# ```
# 59 60 61
# ```

# ### 输出 #1

# ```
# 1
# ```

# ## 输入输出样例 #2

# ### 输入 #2

# ```
# 59 50 59
# ```

# ### 输出 #2

# ```
# 0
# ```

# ## 输入输出样例 #3

# ### 输入 #3

# ```
# 100 100 90
# ```

# ### 输出 #3

# ```
# 0
# ```

##方法1:
c, s, y = map(int, input().split())
count = 0

if c < 60:
    count += 1
if s < 60:
    count += 1
if y < 60:
    count += 1

if count == 1:  # 恰好有一门不及格
    print('1')
else:
    print('0')

##方法2:
c, s, y = map(int, input().split())
# 将布尔值转换为整数（True=1, False=0）然后求和
count = (c < 60) + (s < 60) + (y < 60)

if count == 1:
    print('1')
else:
    print('0')

##方法3:
c, s, y = map(int, input().split())
print('1' if sum(x < 60 for x in [c, s, y]) == 1 else '0')